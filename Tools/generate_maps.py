from pathlib import Path
from pytoc import TOCFile

from dm_tools import WDTReader, WDT, MAP_DB2, Map

self_path = Path(__file__).parent

log_path = self_path / "logs"
log_path.mkdir(parents=True, exist_ok=True)

with open(self_path / "cfg.yaml") as f:
    log_config = yaml.safe_load(f.read())
logging.config.dictConfig(log_config)

queue_handler = logging.getHandlerByName("queue_handler")
if queue_handler is not None:
    queue_handler.listener.start()
    atexit.register(queue_handler.listener.stop)

logger = logging.getLogger(__name__)
logger.info(
    f"Using Python version {sys.version}",
)

MAX_THREADS = os.cpu_count()

parent_directory = Path.cwd()
ADDON_DIR = parent_directory / "Datamine_Maps"
OUTPUT_DIR = ADDON_DIR / "Generated"

OUTPUT_DIR.mkdir(parents=True, exist_ok=True)

LUA_FORMAT = """-- This file was generated by generate_maps.py
-- WDTFileDataID: {wdtFileDataID}
-- Map Name: {map_name}

local _, Datamine_Maps = ...;

Datamine_Maps[{wdtFileDataID}] = {{
    {map_info}
}};
"""


def tabs(depth: int):
    return "\t" * depth

def add_map_files_to_toc():
	toc_path = Path(ADDON_DIR) / "Datamine_Maps.toc"
	toc = TOCFile(toc_path)
	generated_files = [f"Generated/{d.name}" for d in OUTPUT_DIR.iterdir() if d.name.endswith(".lua")]

	existing_files = set(toc.get_all_addon_file_names())
	for file in generated_files:
		if file not in existing_files:
			toc.add_file(file)

	toc.export(toc_path, overwrite=True)

def lua_format(wdtFileDataID: int, map_name: str, map_info: str):
    return LUA_FORMAT.format(
        wdtFileDataID=wdtFileDataID, map_name=map_name, map_info=map_info
    )


def format_map_grids(map_grids: list[WDT]):
    all_grids = "{"

    # map textures
    mapTextures = f"\n{tabs(2)}MapTextures = {{"
    mapTexturesN = f"\n{tabs(2)}MapTexturesN = {{"
    minimapTextures = f"\n{tabs(2)}MinimapTextures = {{"
    i = 1
    for grid in map_grids:
        if int(grid.mapTexture) != 0:
            mapTextures += f"\n{tabs(3)}[{i}]={grid.mapTexture},"

        if int(grid.mapTextureN) != 0:
            mapTexturesN += f"\n{tabs(3)}[{i}]={grid.mapTextureN},"

        if int(grid.minimapTexture) != 0:
            minimapTextures += f"\n{tabs(3)}[{i}]={grid.minimapTexture},"
        i += 1

    mapTextures += f"\n{tabs(2)}}},"
    mapTexturesN += f"\n{tabs(2)}}},"
    minimapTextures += f"\n{tabs(2)}}},"

    all_grids += mapTextures
    all_grids += mapTexturesN
    all_grids += minimapTextures
    all_grids += f"\n{tabs(1)}}}"

    return all_grids


def format_map_info(map: Map, map_grids_str: str) -> str:
    map_info = f"""MapName = "{map.MapName_lang}",
    MapID = {map.ID},
    Directory = [[{map.Directory}]],
    MapDescription0 = [[{map.MapDescription0_lang}]],
    MapDescription1 = [[{map.MapDescription1_lang}]],
    MapType = {map.MapType},
    InstanceType = {map.InstanceType},
    ExpansionID = {map.ExpansionID},
    ParentMapID = {map.ParentMapID},
    CosmeticParentMapID = {map.CosmeticParentMapID},
    Grids = {map_grids_str}"""

    return map_info


def write_map_file(map: Map, reader: WDTReader):
    if map.WdtFileDataID is None:
        return

    fdid = int(map.WdtFileDataID)
    if fdid == 0:
        return

    map_grids = reader.get_file_info(fdid)

    if not map_grids or len(map_grids) == 0:
        logger.error(f"No grids found for map {map.ID} ({map.MapName_lang}) with WDTFileDataID {fdid}")
        return

    map_grids_str = format_map_grids(map_grids)
    map_info = format_map_info(map, map_grids_str)

    map_name = map.Directory.replace(" ", "")
    output_file = os.path.join(OUTPUT_DIR, f"Map_{map_name}.lua")
    with open(output_file, "w") as f:
        f.write(lua_format(wdtFileDataID=fdid, map_name=map_name, map_info=map_info))
        logger.info(f"Wrote map file for {map.ID} ({map.MapName_lang}) with WDTFileDataID {fdid} to {output_file}")

def main():
    flavor = "wowt"
    wow_dir = "F:/Games/World of Warcraft"
    online = False
    if len(sys.argv) > 1:
        flavor = sys.argv[1]
    if len(sys.argv) > 2:
        wow_dir = sys.argv[2]

    wdt_reader = WDTReader(wow_path=wow_dir, product=flavor, online=online)
    maps = MAP_DB2

    _maps = []
    for map in maps.read():
        _maps.append(map)

    logger.info(f"Generating minimaps for {len(_maps)} maps...")

    for e in _maps:
        write_map_file(e, wdt_reader)

    add_map_files_to_toc()

if __name__ == "__main__":
    main()
